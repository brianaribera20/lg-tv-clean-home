"""Turn square app icons into full 360x202 tiles so the colour fills the whole card.

The TV's browser cannot read pixels from local images (the canvas is tainted), so
Home falls back to a grey card with a shrunken logo. Here, on the computer, each
opaque icon is placed on its own edge colour (or a blurred copy of itself when the
edge isn't one colour) and saved as icons/<id>-tile.png; apps.js is pointed at it.
Transparent system glyphs are left alone. Safe to rerun.
"""
import json
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1] / 'launcher'
W, H = 360, 202
LOGO = 170  # icon height inside the tile


def border(im):
    w, h = im.size
    pts = [(x, y) for x in range(w) for y in (1, h - 2)] + [(x, y) for y in range(h) for x in (1, w - 2)]
    return [im.getpixel(p) for p in pts]


def tile(src):
    icon = Image.open(src).convert('RGBA')
    edge = border(icon)
    opaque = [p for p in edge if p[3] > 200]
    if len(opaque) < len(edge) * 0.5:
        return None, None  # transparent glyph: keep the stock look
    avg = tuple(sum(p[i] for p in opaque) // len(opaque) for i in range(3))
    spread = max(max(p[i] for p in opaque) - min(p[i] for p in opaque) for i in range(3))
    if spread <= 24:
        bg = Image.new('RGBA', (W, H), avg + (255,))
    else:
        scale = max(W / icon.width, H / icon.height)
        cover = icon.resize((round(icon.width * scale), round(icon.height * scale)), Image.LANCZOS)
        left, top = (cover.width - W) // 2, (cover.height - H) // 2
        bg = Image.new('RGBA', (W, H), avg + (255,))
        bg.alpha_composite(cover.crop((left, top, left + W, top + H)).filter(ImageFilter.GaussianBlur(18)))
    logo = icon.resize((LOGO, LOGO), Image.LANCZOS)
    bg.alpha_composite(logo, ((W - LOGO) // 2, (H - LOGO) // 2))
    return bg.convert('RGB'), '#%02x%02x%02x' % avg


def accent(src, bg):
    """The logo's main colour: the most common colour clearly different from the tile background."""
    icon = Image.open(src).convert('RGBA')
    bins = {}
    for r, g, b, a in icon.getdata():
        if a < 200 or sum((x - y) ** 2 for x, y in zip((r, g, b), bg)) < 90 ** 2:
            continue
        key = (r // 32, g // 32, b // 32)
        n, sr, sg, sb = bins.get(key, (0, 0, 0, 0))
        bins[key] = (n + 1, sr + r, sg + g, sb + b)
    total = icon.width * icon.height
    if not bins or max(v[0] for v in bins.values()) < total * 0.01:
        return (255, 255, 255)
    n, sr, sg, sb = max(bins.values(), key=lambda v: v[0])
    return (sr // n, sg // n, sb // n)


def hexcolour(rgb):
    return '#%02x%02x%02x' % tuple(rgb)


def main():
    path = ROOT / 'apps.js'
    text = path.read_text()
    data = json.loads(text[text.index('{'):].rstrip().rstrip(';'))
    made = 0
    colours = {}
    for app in data['apps']:
        icon = app.get('icon') or ''
        original = icon.replace('-tile.png', '.png') if icon.endswith('-tile.png') else icon
        if not original.startswith('icons/') or not (ROOT / original).exists():
            continue
        image, colour = tile(ROOT / original)
        if image is None:
            app['icon'] = original
            base = app.get('iconColor') or '#8e8e93'
            colours[app['id']] = [base, '#ffffff']
            continue
        bg = tuple(int(colour[i:i + 2], 16) for i in (1, 3, 5))
        colours[app['id']] = [colour, hexcolour(accent(ROOT / original, bg))]
        name = original[:-4] + '-tile.png'
        image.save(ROOT / name, optimize=True)
        app['icon'], app['iconColor'] = name, colour
        made += 1
    path.write_text('// Generated by sync-apps.py: the TV\'s apps and inputs. Tiles from make-tiles.py.\nwindow.TV_APPS = ' + json.dumps(data, ensure_ascii=False) + ';\n')
    (ROOT / 'app-colors.js').write_text('// Generated by make-tiles.py: [tile colour, logo colour] per app, for the background orbs.\n'
                                        'window.APP_COLORS = ' + json.dumps(colours) + ';\n')
    print(f'Made {made} full tiles.')


if __name__ == '__main__':
    main()
